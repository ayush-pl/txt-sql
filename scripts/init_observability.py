"""One-time: generate local secrets for the observability stack.

Writes observability/.env (Docker Compose secrets, Langfuse admin login) and adds the Langfuse
API keys to the repo .env so the API can send traces. Both files are gitignored. Existing values
are kept, so rerunning is safe. Secrets are never printed.

    python scripts/init_observability.py
"""

from __future__ import annotations

import secrets
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OBS_ENV = REPO / "observability" / ".env"
APP_ENV = REPO / ".env"


def read_env(p: Path) -> dict[str, str]:
    if not p.exists():
        return {}
    out = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def write_env(p: Path, values: dict[str, str], header: str) -> None:
    p.write_text(header + "\n" + "\n".join(f"{k}={v}" for k, v in values.items()) + "\n", encoding="utf-8")


def main() -> None:
    obs = read_env(OBS_ENV)
    defaults = {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_PASSWORD": secrets.token_hex(16),
        "MINIO_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_SALT": secrets.token_hex(16),
        "LANGFUSE_ENCRYPTION_KEY": secrets.token_hex(32),  # 64 hex chars, required by Langfuse
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "LANGFUSE_PUBLIC_KEY": "pk-lf-" + secrets.token_hex(16),
        "LANGFUSE_SECRET_KEY": "sk-lf-" + secrets.token_hex(16),
        "LANGFUSE_ADMIN_EMAIL": "admin@sqlforge.local",
        "LANGFUSE_ADMIN_PASSWORD": secrets.token_urlsafe(18),
        "GRAFANA_ADMIN_PASSWORD": secrets.token_urlsafe(18),
    }
    for k, v in defaults.items():
        obs.setdefault(k, v)
    write_env(OBS_ENV, obs, "# Generated by scripts/init_observability.py - local dev secrets, never commit.")

    app = read_env(APP_ENV)
    # 127.0.0.1, not localhost: on Windows the IPv6-first lookup of "localhost" adds ~2 s per call
    app.update({
        "LANGFUSE_HOST": "http://127.0.0.1:3000",
        "LANGFUSE_PUBLIC_KEY": obs["LANGFUSE_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": obs["LANGFUSE_SECRET_KEY"],
    })
    app.setdefault("VLLM_BASE_URL", "http://127.0.0.1:8000/v1")
    app.setdefault("MODEL_NAME", "sqlforge")
    write_env(APP_ENV, app, "# Local settings - never commit.")
    print(f"wrote {OBS_ENV.relative_to(REPO)} and Langfuse keys into {APP_ENV.relative_to(REPO)} "
          "(Langfuse / Grafana logins are in observability/.env)")


if __name__ == "__main__":
    main()
